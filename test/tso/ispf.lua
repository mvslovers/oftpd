-- test/tso/ispf.lua -- the ISPF dialog: ISPF, More (M), OFTP (O), then
-- the menu, the monitor and the transfer list. Needs OFTPD running and
-- the dialog installed (panels in ISPPLIB, OFTPI in ISPLLIB).
local function show(t, title)
  print("==== " .. title)
  print(t:text())
end

return function(t)
  t:logon()
  t:type("ISPF"):enter()
  t:expect("Primary Option Menu", { timeout = 30 })
  t:type("M"):enter()
  t:expect("Additional Products")
  show(t, "more")
  t:type("O"):enter()
  t:expect("OFTPD - Odette File Transfer", { timeout = 30 })
  show(t, "menu")
  t:type("5"):enter()
  t:expect("OFTPD - Monitor")
  show(t, "monitor")
  t:pf(3)
  t:expect("OFTPD - Odette File Transfer")
  t:type("2"):enter()
  t:expect("OFTPD - Transfers")
  show(t, "transfers")
  t:pf(3)
  t:expect("OFTPD - Odette File Transfer")
  t:type("3"):enter()
  t:expect("OFTPD - Partners")
  show(t, "partners")
  t:pf(3)
  t:expect("OFTPD - Odette File Transfer")

  -- send held: partner, data set, (virtual name), text Y, translate N, hold Y
  t:type("1"):enter()
  t:expect("OFTPD - Send a Data Set")
  t:type("MAC1"):tab()
  t:type("IBMUSER.OFTPD.SAMPLE"):tab()
  t:type("ISPF.TEST"):tab()
  t:type("Y"):tab()
  t:type("N"):tab()
  t:type("Y"):enter()
  t:expect("queued and held")
  show(t, "send")
  t:pf(3)
  t:expect("OFTPD - Odette File Transfer")

  -- the list, filtered to HELD; D on the first row deletes it
  t:type("2"):enter()
  t:expect("OFTPD - Transfers")
  t:tab():tab():tab()
  t:type("HELD"):enter()
  t:expect("1 transfers")
  show(t, "held")
  t:tab():tab():tab():tab():tab()
  t:type("D"):enter()
  t:expect("deleted")
  show(t, "deleted")
  t:pf(3)
  t:expect("OFTPD - Odette File Transfer")
  t:pf(3)
  t:pf(3)
  t:expect("Primary Option Menu")
  t:type("X"):enter()
  t:logoff()
end
